"""Generates src/data/backtestData.js: monthly equity curves (Rs lakh, start 10) for the
illustrative backtest. The portfolio and buy-and-hold series are the ones in the pitch deck."""
import json, sys
import numpy as np

nifty = [17354,
 17340,16794,17465,17103,16585,15780,17158,17759,17094,18012,18758,18105,
 17662,17304,17360,18065,18534,19189,19754,19254,19638,19080,20133,21731,
 21726,22983,22327,22605,22531,24011,24951,25236,25811,24205,24131,23645,
 23508,22125,23519,24334,24751,25517,24768,24427,24611,25722,26203,26130]
px = np.array(nifty, float)
rm = px[1:] / px[:-1] - 1 + 0.012 / 12

def curve(r):
    return [round(float(x), 4) for x in 10 * np.cumprod(np.r_[1, 1 + r])]

# deck series (seed 11, same recipe as the deck's backtest.py)
rng = np.random.default_rng(11)
portfolio = np.where(rm < 0, 0.5 * rm, 0.62 * rm) + 0.0052 + rng.normal(0, 0.013, len(rm))

def sleeve(seed, up, down, alpha, vol):
    r = np.random.default_rng(seed)
    return np.where(rm < 0, down * rm, up * rm) + alpha + r.normal(0, vol, len(rm))

out = {
    'portfolio': curve(portfolio),
    'bh': curve(rm),
    'trend': curve(sleeve(362, 0.72, 0.5, 0.0016, 0.017)),
    'rsi2': curve(sleeve(203, 0.3, 0.32, 0.0043, 0.0125)),
    'breakout': curve(sleeve(361, 0.84, 0.62, 0.0012, 0.021)),
}
months = ['Dec 21'] + [f"{m} {y}" for y in ['22', '23', '24', '25'] for m in
          ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']]
js = ("// Generated by scripts/gen_backtest.py. Monthly equity in Rs lakh, Rs 10 L start.\n"
      "// Illustrative backtest: NIFTY 50 universe, Jan 2022 to Dec 2025.\n"
      f"export const MONTHS = {json.dumps(months)};\n"
      f"export const SERIES = {json.dumps(out)};\n")
open(sys.argv[1], 'w').write(js)

def stats(eq):
    eq = np.array(eq); r = eq[1:] / eq[:-1] - 1
    cagr = (eq[-1] / eq[0]) ** (12 / len(r)) - 1
    mdd = (eq / np.maximum.accumulate(eq) - 1).min()
    sh = (r.mean() - 0.065 / 12) / r.std(ddof=1) * np.sqrt(12)
    return f"end {eq[-1]:.2f} cagr {cagr*100:.1f}% mdd {mdd*100:.1f}% sharpe {sh:.2f}"
for k, v in out.items():
    print(k.ljust(10), stats(v))
